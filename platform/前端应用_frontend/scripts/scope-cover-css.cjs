const fs = require('node:fs')
const path = require('node:path')
const postcss = require('postcss')

const frontendRoot = path.resolve(__dirname, '..')
const sourcePath = path.join(frontendRoot, 'src', 'cover', 'styles.css')
const outputPath = path.join(frontendRoot, 'src', 'cover', 'styles.scoped.css')
const scope = '.cover-app'

function scopeSelector(selector) {
  const value = selector.trim()
  if (!value) return scope
  if (value === ':root' || value === 'html' || value === 'body') return scope
  if (value.startsWith('body')) {
    const suffix = value.slice(4).trim()
    return suffix ? `${scope}${suffix}` : scope
  }
  if (value === '*') return `${scope} *`
  return value.startsWith(scope) ? value : `${scope} ${value}`
}

const css = fs.readFileSync(sourcePath, 'utf8')
const root = postcss.parse(css)

root.walkRules((rule) => {
  const parent = rule.parent
  if (
    parent
    && parent.type === 'atrule'
    && /keyframes$/i.test(parent.name)
  ) {
    return
  }
  rule.selectors = [...new Set(rule.selectors.map(scopeSelector))]
})

const banner = [
  '/* Generated by scripts/scope-cover-css.cjs.',
  '   Source: src/cover/styles.css. Do not edit this file directly. */',
  '',
].join('\n')

fs.writeFileSync(outputPath, banner + root.toString(), 'utf8')
console.log(`scoped cover css -> ${path.relative(frontendRoot, outputPath)}`)
